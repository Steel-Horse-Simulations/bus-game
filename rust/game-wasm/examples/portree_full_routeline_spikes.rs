// Throwaway: reproduce `routeLine()` from src/renderer/route-panel.ts (the
// function that renders every SAVED route's own band on the map, via
// pairwise `find_route` per leg with no de-dup at leg boundaries) for
// every real Skye depot-group route near Portree Depot, using the exact
// point sequences pulled live from the player's own save.sqlite (depot
// group 22, routes 40/41/57/58/63/66/67/74/80). Flags any spike within
// 700m of the depot (-6.2106972, 57.4202675).
use game_wasm::Router;
use std::fs;

const DEPOT: (f64, f64) = (-6.2106972, 57.4202675);

fn dist_m(a: (f64, f64), b: (f64, f64)) -> f64 {
    let r = 6371000.0;
    let lat1 = a.1.to_radians();
    let lat2 = b.1.to_radians();
    let dlat = lat2 - lat1;
    let dlon = (b.0 - a.0).to_radians();
    let x = dlon * ((lat1 + lat2) / 2.0).cos();
    r * (dlat * dlat + x * x).sqrt()
}

fn routeline_style(router: &Router, seq: &[(f64, f64)]) -> Vec<(f64, f64)> {
    let mut out = Vec::new();
    for i in 0..seq.len().saturating_sub(1) {
        let (a, b) = (seq[i], seq[i + 1]);
        let flat = router.find_route(a.0, a.1, b.0, b.1);
        if flat.is_empty() {
            continue;
        }
        out.extend(flat.chunks(2).map(|c| (c[0], c[1])));
    }
    out
}

fn report_spikes(label: &str, pts: &[(f64, f64)]) {
    let mut any = false;
    for i in 1..pts.len().saturating_sub(1) {
        let (pa, pb, pc) = (pts[i - 1], pts[i], pts[i + 1]);
        let detour = dist_m(pa, pb) + dist_m(pb, pc) - dist_m(pa, pc);
        let direct = dist_m(pa, pc);
        if detour > 5.0 && direct < 40.0 && dist_m(pb, DEPOT) < 700.0 {
            any = true;
            println!(
                "[{label}] SPIKE idx {i}: detour={detour:.1}m direct={direct:.1}m depot_dist={:.0}m  a={pa:?} b={pb:?} c={pc:?}",
                dist_m(pb, DEPOT)
            );
        }
    }
    if !any {
        println!("[{label}] no spike within 700m of depot");
    }
}

